<?php

namespace App\Support;

/**
 * Приведение названий образовательных организаций ("Кем выдан" в документе об образовании)
 * к единому виду для отчетов. Данные в базе не меняются - только то, что выводится в отчет.
 *
 * Чтобы добавить организацию, допишите строку в RULES: [регулярное выражение, итоговое название].
 * Регулярное выражение применяется к названию в нижнем регистре, "ё" заменена на "е",
 * кавычки и лишние пробелы уже убраны. Правила проверяются сверху вниз, срабатывает первое.
 */
class EducationOrganizationName
{
    public const IUBIP = 'ЧОУ ВО «Южный университет (ИУБиП)»';
    public const IUBIP_SALSK = 'ЧПОУ «Сальский институт Южного Университета (ИУБиП)»';
    public const IUBIP_DONETSK = 'ЧПОУ «Донецкий институт Южного Университета (ИУБиП)»';

    private const RULES = [
        // Филиалы ИУБиП - раньше головной организации, т.к. в их названиях тоже есть "Южного Университета"
        ['/\bсальский институт\b.*(иубип|юу|южн\w+\s+[иу]ниверситет)|\bси юу\b/u', self::IUBIP_SALSK],
        ['/\bдонецк\w*\s+(институт|колледж)\b.*(иубип|юу|южн\w+\s+[иу]ниверситет)|\bди юу\b/u', self::IUBIP_DONETSK],

        // Головная организация: ИУБиП, "Южный университет", опечатки ("Иниверситет"), ЧОУ ВО ЮУ, расшифровка названия
        ['/иубип|южн\w+\s+[иу]ниверситет|чоу\s+во\s+юу|институт\s+управления,?\s+бизнеса\s+и\s+права/u', self::IUBIP],

        // Распространённые сокращения и варианты написания других вузов
        ['/^юфу$|южн\w*\s+федер\w+\s+университет/u', 'ФГАОУ ВО «Южный федеральный университет»'],
        ['/^дгту$|донской государственный технический университет/u', 'ФГБОУ ВО «Донской государственный технический университет»'],
        ['/^ринх$|ростовский государственный экономический университет/u', 'ФГБОУ ВО «Ростовский государственный экономический университет (РИНХ)»'],
        ['/^ргупс$|ростовский государственный университет путей сообщения/u', 'ФГБОУ ВО «Ростовский государственный университет путей сообщения»'],
        ['/^ргму$|ростовский государственный медицинский университет/u', 'ФГБОУ ВО «Ростовский государственный медицинский университет»'],
    ];

    public static function normalize(?string $name): string
    {
        $name = trim(preg_replace('/\s+/u', ' ', (string)$name));

        if ($name === '') {
            return '';
        }

        // Ключ для сопоставления: нижний регистр, без "ё", без кавычек и лишних знаков по краям
        $key = mb_strtolower(str_replace('ё', 'е', $name));
        $key = trim(preg_replace('/[«»"“”„\']+/u', ' ', $key));
        $key = trim(preg_replace('/\s+/u', ' ', $key), " .,;");

        foreach (self::RULES as [$pattern, $canonical]) {
            if (preg_match($pattern, $key)) {
                return $canonical;
            }
        }

        return self::tidyQuotes($name);
    }

    /** Прямые кавычки -> «ёлочки», если их чётное число (иначе оставляем как есть) */
    private static function tidyQuotes(string $name): string
    {
        $name = str_replace(['“', '”', '„'], '"', $name);

        if (substr_count($name, '"') === 0 || substr_count($name, '"') % 2 !== 0) {
            return $name;
        }

        $open = true;

        return preg_replace_callback('/"/u', function () use (&$open) {
            $result = $open ? '«' : '»';
            $open = !$open;

            return $result;
        }, $name);
    }
}